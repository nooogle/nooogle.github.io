#!/usr/bin/env python3
"""Build hiragana/vendor/kanjivg-hiragana.js, the stroke order data, from KanjiVG.

Downloads one SVG per kana in the deck (js/deck.js) from a fixed KanjiVG release and keeps just
the stroke paths, in order, and where each stroke number goes. Run it from the top of the repo:

    python3 tools/make_strokes.py r20260714

Then rebuild the offline cache list (tools/make_sw.py), since the data file will have changed.
"""
import sys, re, json, urllib.request
tag = sys.argv[1]
deck = open('hiragana/js/deck.js', encoding='utf-8').read()
kana = ''.join(re.findall(r"\{id:'\w+',k:'([^']+)'", deck))
data = {}
for k in kana:
    url = 'https://raw.githubusercontent.com/KanjiVG/kanjivg/%s/kanji/%05x.svg' % (tag, ord(k))
    svg = urllib.request.urlopen(url).read().decode('utf-8')
    strokes = re.findall(r'<path id="kvg:[0-9a-f]+-s\d+"[^>]* d="([^"]+)"', svg)
    nums = [[float(x), float(y)] for x, y in re.findall(r'<text transform="matrix\(1 0 0 1 ([\d.]+) ([\d.]+)\)">\d+</text>', svg)]
    if not strokes or len(strokes) != len(nums):
        sys.exit('Unexpected file for %s: %d strokes, %d numbers' % (k, len(strokes), len(nums)))
    data[k] = {'s': strokes, 'n': nums}
    print(k, len(strokes))
out = """// Stroke order for every hiragana in the deck: each stroke's path, in order, and where its number goes.
// Generated by tools/make_strokes.py from KanjiVG %s (https://kanjivg.tagaini.net/), drawn in a 109 x 109 box.
// KanjiVG is copyright (C) Ulrich Apel and is shared under CC BY-SA 3.0, and so is this file:
// see kanjivg-LICENSE.txt. Don't edit by hand; rerun the script instead.
export const STROKES=%s;
""" % (tag, json.dumps(data, ensure_ascii=False, separators=(',', ':')))
open('hiragana/vendor/kanjivg-hiragana.js', 'w', encoding='utf-8').write(out)
print(len(data), 'kana written')
